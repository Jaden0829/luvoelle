const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('luvoelle', {
  bootstrap: () => ipcRenderer.invoke('app:bootstrap'),
  assistantBootstrap: () => ipcRenderer.invoke('assistant:bootstrap'),
  assistantHover: (hovered) => ipcRenderer.invoke('assistant:hover', hovered),
  assistantOpen: () => ipcRenderer.invoke('assistant:open'),
  assistantToggle: () => ipcRenderer.invoke('assistant:toggle'),
  assistantCollapse: () => ipcRenderer.invoke('assistant:collapse'),
  assistantShow: (payload) => ipcRenderer.invoke('assistant:show', payload),
  assistantHide: () => ipcRenderer.invoke('assistant:hide'),
  assistantDragStart: () => ipcRenderer.invoke('assistant:drag-start'),
  assistantTranslate: (payload) => ipcRenderer.invoke('assistant:translate', payload),
  assistantOcr: (payload) => ipcRenderer.invoke('assistant:ocr', payload),
  startCapture: (mode) => ipcRenderer.invoke('capture:start', mode),
  submitCapture: (payload) => ipcRenderer.invoke('capture:submit', payload),
  cancelCapture: () => ipcRenderer.send('capture:cancel'),
  reportOverlayPaint: (payload) => ipcRenderer.send('overlay:paint', payload),
  reportOverlayInteraction: (payload) => ipcRenderer.send('overlay:interaction-sample', payload),
  reportOverlayPreviewReady: (payload) => ipcRenderer.send('overlay:preview-ready', payload),
  reportOverlayStandbyReady: () => ipcRenderer.send('overlay:standby-ready'),
  selectImage: () => ipcRenderer.invoke('image:select'),
  processImage: (payload) => ipcRenderer.invoke('image:process', payload),
  translateImage: (payload) => ipcRenderer.invoke('translate:image', payload),
  getOcrStatus: () => ipcRenderer.invoke('ocr:status'),
  translateText: (payload) => ipcRenderer.invoke('translate:text', payload),
  retryTranslation: (payload) => ipcRenderer.invoke('translation:retry', payload),
  applyCorrection: (payload) => ipcRenderer.invoke('result:apply-correction', payload),
  saveSettings: (settings) => ipcRenderer.invoke('settings:save', settings),
  startShortcutRecording: () => ipcRenderer.invoke('shortcuts:recording-start'),
  stopShortcutRecording: () => ipcRenderer.invoke('shortcuts:recording-end'),
  checkVisionService: (settings) => ipcRenderer.invoke('vision:check', settings),
  openPromptHistory: (id) => ipcRenderer.invoke('prompt:open-history', id),
  reanalyzePrompt: (payload) => ipcRenderer.invoke('prompt:reanalyze', payload),
  cancelPromptAnalysis: (jobId) => ipcRenderer.invoke('prompt:cancel-analysis', jobId),
  generateReferenceImage: (payload) => ipcRenderer.invoke('prompt:generate', payload),
  saveGeneratedImage: (dataUrl) => ipcRenderer.invoke('prompt:save-image', dataUrl),
  promptAction: (action) => ipcRenderer.invoke('prompt:action', action),
  deleteHistory: (id) => ipcRenderer.invoke('history:delete', id),
  clearHistory: () => ipcRenderer.invoke('history:clear'),
  copyText: (text) => ipcRenderer.invoke('clipboard:write', text),
  copyImage: (dataUrl) => ipcRenderer.invoke('editor:copy', dataUrl),
  getClipboardImage: () => ipcRenderer.invoke('clipboard:image'),
  openMain: () => ipcRenderer.invoke('window:open-main'),
  windowControl: (action) => ipcRenderer.invoke('window:control', action),
  floatAction: (action) => ipcRenderer.invoke('float:action', action),
  openImageEditor: (payload) => ipcRenderer.invoke('editor:open', payload),
  copyEditedImage: (dataUrl) => ipcRenderer.invoke('editor:copy', dataUrl),
  saveEditedImage: (dataUrl) => ipcRenderer.invoke('editor:save', dataUrl),
  pinEditedImage: (payload) => ipcRenderer.invoke('pin:create', payload),
  closeImageEditor: () => ipcRenderer.invoke('editor:close'),
  closePinnedImage: () => ipcRenderer.invoke('pin:close'),
  onOverlayInit: (callback) => ipcRenderer.on('overlay:init', (_event, value) => callback(value)),
  onOverlayPrepare: (callback) => ipcRenderer.on('overlay:prepare', (_event, value) => callback(value)),
  onOverlayTargetsUpdate: (callback) => ipcRenderer.on('overlay:targets-update', (_event, value) => callback(value)),
  onOverlayStandby: (callback) => ipcRenderer.on('overlay:standby', () => callback()),
  onJobEvent: (callback) => ipcRenderer.on('job:event', (_event, value) => callback(value)),
  onNavigate: (callback) => ipcRenderer.on('app:navigate', (_event, value) => callback(value)),
  onEditorInit: (callback) => ipcRenderer.on('editor:init', (_event, value) => callback(value)),
  onPinnedImageInit: (callback) => ipcRenderer.on('pin:init', (_event, value) => callback(value)),
  onPromptEvent: (callback) => ipcRenderer.on('prompt:event', (_event, value) => callback(value)),
  onWindowState: (callback) => ipcRenderer.on('window:state', (_event, value) => callback(value)),
  onHistoryUpdated: (callback) => ipcRenderer.on('history:updated', (_event, value) => callback(value)),
  onAssistantState: (callback) => ipcRenderer.on('assistant:state', (_event, value) => callback(value)),
});
